export type BatchCopyKey = keyof typeof BATCH_COPY;

export function batchCopy(key: BatchCopyKey, language: Language): string {
  const row = BATCH_COPY[key];
  return language === "fr" ? row.fr : row.en;
}

export function batchPhrase(key: BatchCopyKey, language: Language, values: Record<string, string | number> = {}): string {
  return batchCopy(key, language).replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  );
}

export function batchPair(key: BatchCopyKey): Record<Language, string> {
  return { en: batchCopy(key, "en"), fr: batchCopy(key, "fr") };
}
